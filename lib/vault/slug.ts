/**
 * Слаг сервиса из его названия.
 *
 * Отдельным файлом, а не внутри экрана: во-первых, это чистая функция без
 * React, во-вторых, таблица транслитерации — данные, а не текст интерфейса, и в
 * `components/` её справедливо ловит проверка локализации (`npm run i18n:check`).
 *
 * Слаг нужен потому, что по нему машина просит ключ (`vendorKeys`): имя правят,
 * а идентификатор в запросе ноды меняться не должен.
 */

/**
 * Кириллица транслитерируется, а не выбрасывается: сервис вполне заведут как
 * «Яндекс SpeechKit», и выброшенная кириллица оставила бы слаг «speechkit» —
 * похожий на чужой. Слаг обязан остаться латинским: он едет в запрос ноды.
 */
const TRANSLIT: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z",
  и: "i", й: "y", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r",
  с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "c", ч: "ch", ш: "sh", щ: "sch",
  ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
}

/** «ElevenLabs» → `elevenlabs`, «Яндекс SpeechKit» → `yandeks-speechkit`. */
export function slugify(raw: string): string {
  return raw
    .toLowerCase()
    .split("")
    .map((ch) => TRANSLIT[ch] ?? ch)
    .join("")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60)
}
