-- Страховочный обход папок IN по каталогу.
--
-- Зачем: сборка задач идёт по журналу (lib/pipeline/scan.ts) — «элемент попал в
-- очередь в момент своего события». Это односторонняя схема: курсор
-- automation_scan_state.last_seq двигается независимо от того, создалась задача
-- или нет, поэтому любой пропуск окончательный. Проект был на паузе, гейт
-- владельца выключен, options.json битый, в коде ошибка — файл остаётся лежать в
-- IN навсегда, и никакое последующее исправление его не подберёт: новых событий
-- по нему уже не будет.
--
-- Старый десктопный перебор папок этой болезнью не страдал: он был идемпотентен
-- по СОСТОЯНИЮ, а не по событиям, и файл находился на каждом проходе, пока лежал
-- в папке. Обход возвращает это свойство второй линией — по расписанию, по
-- каталогу (project_files), без листинга R2. Первая линия остаётся событийной:
-- она даёт задачу через секунды, а не через четверть часа.

ALTER TABLE automation_scan_state
  -- Одно поле на всё расписание: период в минутах, 0 — обход по таймеру
  -- выключен. Отдельного тумблера нет намеренно — тумблер рядом с периодом это
  -- два переключателя на одно решение, и «включён, но раз в сутки» от
  -- «выключен» ничем содержательно не отличается.
  ADD COLUMN IF NOT EXISTS sweep_interval_min INTEGER NOT NULL DEFAULT 15,
  -- Когда обход проходил последний раз. По нему же цикл решает, пора ли:
  -- срок считается от конца прошлого обхода, а не от старта слежения.
  ADD COLUMN IF NOT EXISTS swept_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS last_swept INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS last_sweep_error TEXT;

-- Границы: 0 — выключено, минута снизу, чтобы обход не превратился во второй
-- событийный сканер, сутки сверху — реже уже не страховка.
ALTER TABLE automation_scan_state
  DROP CONSTRAINT IF EXISTS automation_scan_state_sweep_interval_chk;
ALTER TABLE automation_scan_state
  ADD CONSTRAINT automation_scan_state_sweep_interval_chk
  CHECK (sweep_interval_min = 0 OR sweep_interval_min BETWEEN 1 AND 1440);

-- Обход спрашивает «есть ли по этому элементу задача» ключом источника, и
-- спрашивает это на каждый элемент каждой папки IN. Существующий
-- tasks_active_source_idx частичный (только живые статусы), поэтому для вопроса
-- «была ли задача вообще, включая done и failed» он не годится.
CREATE INDEX IF NOT EXISTS tasks_source_key_idx
  ON tasks (project_id, source_key);
