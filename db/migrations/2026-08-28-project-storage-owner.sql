-- Префикс объекта в R2 отвязывается от владельца проекта.
--
-- Ключи имеют вид `projects/{userId}/{projectId}/…`, и до сих пор `{userId}` был
-- одновременно двумя вещами: где лежат байты и кому проект принадлежит. Пока
-- проект нельзя было передать другому человеку, различие ничего не стоило.
-- С передачей оно становится главным: сменить владельца — это одна строка в
-- базе, а перенести байты — минуты копирования, окно «половина там, половина
-- тут» и полная перезаливка зеркал на всём парке машин (ключи в `getDelta`
-- изменились бы у каждого файла).
--
-- Поэтому разводим два вопроса по двум колонкам:
--
--   projects.user_id           — кто владелец сейчас   (меняется при передаче)
--   projects.storage_owner_id  — где лежат байты       (не меняется никогда)
--
-- Права по-прежнему считаются от user_id и project_members; storage_owner_id в
-- проверках доступа не участвует и участвовать не должен — это адрес, а не
-- полномочие. Разбор — docs/ADMIN_WORKSPACE_PLAN.md §5.
--
-- NOT NULL сознательно не ставим: колонка читается через
-- COALESCE(storage_owner_id, user_id), поэтому и незаполненная строка, и выкатка
-- кода раньше миграции ведут себя как до неё. Ужесточать — отдельным файлом,
-- когда бэкфилл заведомо прошёл везде.

ALTER TABLE projects
  ADD COLUMN IF NOT EXISTS storage_owner_id TEXT REFERENCES users(id);

UPDATE projects
   SET storage_owner_id = user_id
 WHERE storage_owner_id IS NULL;
