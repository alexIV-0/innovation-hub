-- Срок копии ключа — у УЧЁТКИ, а не только у сервиса.
--
-- «Сколько живёт копия» — свойство конкретного ключа, а не сервиса целиком: у
-- одного вендора рядом живут наш рабочий ключ и клиентский, и держать их на
-- машине одинаково долго незачем. Клиентский разумно отзывать быстрее — он
-- чужой, и цена его утечки не наша.
--
-- NULL — «как у сервиса». Так у всех уже заведённых учёток, и поведение не
-- меняется ни для одной: выдача берёт COALESCE(учётка, сервис).
ALTER TABLE vendor_accounts
  ADD COLUMN IF NOT EXISTS key_ttl_sec INTEGER
  CHECK (key_ttl_sec IS NULL OR key_ttl_sec BETWEEN 60 AND 604800);
