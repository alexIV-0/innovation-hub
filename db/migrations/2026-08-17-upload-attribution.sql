-- Атрибуция загрузки: кто принёс файл и каким именем он подписан в статистике.
--
-- Зачем: `description.contact` задачи должен называть того, кто залил файл, а не
-- то, что вписано в узел `description` графа. Локально это поле заполняют руками,
-- потому что там заливать некому; в расшаренном проекте файлы приносят
-- приглашённые, и «к кому идти с вопросами» знает только сайт.

-- Актор события. В журнале, а не только в project_files, по двум причинам.
--
-- Первая: сканер конвейера (lib/pipeline/scan.ts) идёт по журналу, поэтому
-- личность приезжает вместе с событием — без единого дополнительного запроса.
--
-- Вторая, важнее: для папки виток запускает не тот, кто залил в неё файл, а тот,
-- кто снял `-` с имени, то есть актор `move`-события. Из каталога это не
-- восстановить: в project_files от переименования остаётся только новое имя.
ALTER TABLE storage_changes
  ADD COLUMN IF NOT EXISTS actor_user_id TEXT REFERENCES users(id) ON DELETE SET NULL;

-- Кто залил файл. Отдельно от журнала, потому что журнал ретенционный (90 дней,
-- lib/storage/changes.ts#CHANGE_RETENTION_DAYS), а «кто принёс этот файл» нужно
-- показывать в кабинете и брать в манифест папки — там журнала уже нет.
--
-- Перезапись файла переносит атрибуцию на нового заливщика: задачу создаёт
-- именно его событие. Записи машин парка (`rc_`) её не трогают — иначе возврат
-- результата в проект переназначил бы contact на админа, который зарегистрировал
-- компьютер.
ALTER TABLE project_files
  ADD COLUMN IF NOT EXISTS uploaded_by TEXT REFERENCES users(id) ON DELETE SET NULL;

-- Имя для статистики обработки. Отдельно от full_name: оно должно совпадать со
-- строкой, которой человек подписывается при локальной обработке, а статистика
-- группируется по contact — «Aleksey Ivanov» против «Алексей» расщепят одного
-- человека на два ряда. NULL — берём full_name.
ALTER TABLE users
  ADD COLUMN IF NOT EXISTS contact_name TEXT;
