-- Адрес сервиса (VENDOR_SERVICES_PLAN О5).
--
-- До сих пор адрес был зашит в адаптере на стороне программы — там же, откуда
-- мы забрали прайс, и по той же причине забираем адрес: смена эндпоинта у
-- вендора не должна означать обход парка с переустановкой плагинов.
--
-- Пустая строка, а не NULL: «адрес не задан» и «адрес пустой» — одно и то же
-- состояние, и различать их нечем. Для сервисов, где адрес знает сама нода,
-- поле так и останется пустым.
ALTER TABLE vendor_services
  ADD COLUMN IF NOT EXISTS base_url TEXT NOT NULL DEFAULT '';

-- Секрет становится необязательным.
--
-- Свой ComfyUI, поднятый рядом, может не требовать авторизации вообще: у него
-- есть адрес и нет ключа. Прежнее «сервис без ключа не умеет ничего» было
-- верно для чужих API и неверно для своих. Строка секрета при этом не
-- заводится вовсе — версий у такого сервиса нет, и машине в ответе приходит
-- `hasSecret: false`, а не пустой ключ, который она приняла бы за настоящий.
--
-- Миграции для этого не нужно: `vendor_service_secrets` и так отдельная
-- таблица, и отсутствие строки в ней уже допустимо схемой. Комментарий здесь,
-- чтобы решение не выглядело случайным при чтении схемы.
