-- Конвейер: слежение за пользователем включено по умолчанию.
--
-- В 2026-08-13-pipeline-automation.sql колонка появилась с DEFAULT FALSE из
-- осторожности — чтобы конвейер не начал следить за всеми сразу после миграции.
-- На практике это неверная модель: по умолчанию пользователь участвует в
-- обработке, а гейт нужен, чтобы кого-то ИСКЛЮЧИТЬ. Так же устроено и в
-- десктопном приложении: папка отслеживается, пока её явно не выключили
-- (off-список, см. docs/FOLDER_STATE_SSOT_PLAN.md), а не наоборот.
--
-- Имя файла отсортировано после базовой миграции (pipeline-users > pipeline-
-- automation), иначе runner применил бы её первой, когда колонки ещё нет.

ALTER TABLE users ALTER COLUMN automation_enabled SET DEFAULT TRUE;

-- Разовый бэкфилл. Условие на FALSE, а не безусловный UPDATE: если к моменту
-- применения кого-то уже выключили руками, это решение не отменяем.
UPDATE users SET automation_enabled = TRUE WHERE automation_enabled = FALSE;
