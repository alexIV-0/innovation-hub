-- Разбор упавшей обработки: на какой машине это случилось и где теперь файл.
--
-- Обе колонки появились из одного живого случая: машина упала, а в окне очереди
-- у задачи пустая колонка «Машина» и файл, которого конвейер больше не видит.

-- Какая машина последней держала задачу.
--
-- Отдельно от claimed_by, а не вместо: на claimed_by держится аренда, и все
-- терминальные переходы (failTask, completeTask, releaseTask, reapExpiredLeases)
-- его зануляют — иначе `taskDone` от чужой машины прошёл бы как свой. Из-за
-- этого имя машины исчезало ровно в тот момент, когда оно нужно: у упавшей
-- задачи. last_machine_id ставится при захвате и не чистится никогда.
ALTER TABLE tasks
  ADD COLUMN IF NOT EXISTS last_machine_id TEXT
    REFERENCES remote_computers(id) ON DELETE SET NULL;

-- Живым задачам проставим из аренды: они прямо сейчас на машине, и терять их
-- историю из-за момента накатывания миграции незачем.
UPDATE tasks
   SET last_machine_id = claimed_by
 WHERE claimed_by IS NOT NULL
   AND last_machine_id IS NULL;

-- Когда исходник унесли из IN в папку ошибок.
--
-- NULL — «файл всё ещё лежит в IN». Хранить сам путь нельзя: папка ошибок одна
-- на проект и переименовывается на дату последней ошибки, поэтому записанное имя
-- устарело бы на следующем падении. Дату держим здесь, текущее имя папки всегда
-- есть в каталоге.
ALTER TABLE tasks
  ADD COLUMN IF NOT EXISTS quarantined_at TIMESTAMPTZ;
