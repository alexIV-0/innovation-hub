-- Теги прав админов. Этап 4 плана docs/ADMIN_ROLES_PLAN.md.
--
-- Админы различаются не глубиной прав, а направлением работы: один занимается
-- акциями и подарками, другой по запросу разбирает чужие проекты. Лестницей это
-- не выражается — «выше/ниже» тут нет, есть разные комнаты. Отсюда теги.
--
-- Главное правило, которое таблица одна не удержит и которое живёт в коде:
-- ТЕГИ РАЗДАЮТ ДОСТУП К РАБОТЕ, НО НИКОГДА — К РАЗДАЧЕ ДОСТУПА. Ни один тег не
-- даёт права выдавать теги, менять роли и трогать другого админа. Иначе админ
-- дотянулся бы до суперадмина через сам механизм тегов.
--
-- Суперадмину строки здесь не пишутся: у него теги не проверяются вовсе. Держать
-- ему полный набор — значит завести второй источник правды и однажды с ним
-- разъехаться.
--
-- Таблица, а не массив в users: granted_by и granted_at отвечают на первый
-- вопрос, который задаёт суперадмин, увидев неожиданное, — «кто ему это выдал и
-- когда». В массиве этого нет.

CREATE TABLE IF NOT EXISTS admin_capabilities (
  user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  capability TEXT NOT NULL,
  granted_by TEXT REFERENCES users(id) ON DELETE SET NULL,
  granted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, capability)
);

-- Обратный вопрос: «покажи всех, у кого есть billing.manage».
CREATE INDEX IF NOT EXISTS admin_capabilities_capability_idx
  ON admin_capabilities (capability);
