-- Адрес — у УЧЁТКИ, а не только у сервиса.
--
-- Два ComfyUI, поднятых на разных машинах, — это НЕ два сервиса. Слаг уникален
-- (`vendor_services.slug UNIQUE`), и завести второй сервис с тем же слагом
-- нельзя; а разные слаги означали бы, что под каждую установку нужен свой
-- плагин, хотя API у них одинаковое.
--
-- Правильная развёртка: один сервис `comfy` (его и знает плагин), а установки —
-- это учётки, у каждой свой адрес и свой ключ. Тогда выбор установки в
-- настройках проекта — тот же выпадающий список меток, что и выбор ключа.
--
-- NULL — «как у сервиса»: у вендоров с одним публичным API (ElevenLabs и
-- прочие) адрес общий, и дублировать его в каждой учётке незачем.
ALTER TABLE vendor_accounts
  ADD COLUMN IF NOT EXISTS base_url TEXT;
